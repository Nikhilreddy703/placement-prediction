"""PDF report generation for student placement evaluation using ReportLab."""
import io
from datetime import datetime
from typing import Any, Dict, List

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def generate_student_pdf_report(
    student_profile: Dict[str, Any],
    prediction_result: Dict[str, Any],
    model_name: str = "KNN",
) -> bytes:
    """Generate a high quality PDF evaluation report and return raw bytes."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#0F172A"),
        fontName="Helvetica-Bold",
    )
    subtitle_style = ParagraphStyle(
        "DocSubTitle",
        parent=styles["Normal"],
        fontSize=10,
        textColor=colors.HexColor("#64748B"),
        fontName="Helvetica",
    )
    h2_style = ParagraphStyle(
        "SectionH2",
        parent=styles["Heading2"],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#1E3A8A"),
        fontName="Helvetica-Bold",
        spaceBefore=10,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "Body",
        parent=styles["Normal"],
        fontSize=9.5,
        leading=13,
        textColor=colors.HexColor("#1E293B"),
    )
    rec_style = ParagraphStyle(
        "RecStyle",
        parent=styles["Normal"],
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#0F172A"),
    )

    story = []

    # Document Header
    story.append(Paragraph("Student Placement Prediction & Career Readiness Report", title_style))
    date_str = datetime.now().strftime("%B %d, %Y - %H:%M")
    story.append(Paragraph(f"Generated by Campus Placement Analytics Engine | Date: {date_str}", subtitle_style))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563EB"), spaceAfter=15))

    # Executive Summary Banner Table
    prob = prediction_result.get("probability", 0.5)
    risk_level = prediction_result.get("risk_level", "Moderate Risk")
    status_text = prediction_result.get("status_text", "Placement Evaluation")

    status_color = colors.HexColor("#10B981") if risk_level == "Low Risk" else (
        colors.HexColor("#F59E0B") if risk_level == "Moderate Risk" else colors.HexColor("#EF4444")
    )

    summary_data = [
        [
            Paragraph("<b>Predicted Status</b>", body_style),
            Paragraph(f"<b><font color='{status_color}'>{status_text}</font></b>", body_style),
            Paragraph("<b>Placement Likelihood</b>", body_style),
            Paragraph(f"<b>{prob:.1%}</b>", body_style),
        ],
        [
            Paragraph("<b>Active Model</b>", body_style),
            Paragraph(f"{model_name}", body_style),
            Paragraph("<b>Risk Categorization</b>", body_style),
            Paragraph(f"<b>{risk_level}</b>", body_style),
        ],
    ]
    summary_table = Table(summary_data, colWidths=[120, 150, 120, 140])
    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#CBD5E1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(summary_table)
    story.append(Spacer(1, 15))

    # Academic & Profile Details Table
    story.append(Paragraph("Student Academic & Profile Parameters", h2_style))
    profile_data = [
        ["Parameter", "Student Value", "Parameter", "Student Value"],
        ["10th Marks (SSC %)", f"{student_profile.get('ssc_p', 0):.1f}%", "10th Board", str(student_profile.get("ssc_b", "N/A"))],
        ["12th Marks (HSC %)", f"{student_profile.get('hsc_p', 0):.1f}%", "12th Board / Stream", f"{student_profile.get('hsc_b', 'N/A')} ({student_profile.get('hsc_s', 'N/A')})"],
        ["Graduation (Degree %)", f"{student_profile.get('degree_p', 0):.1f}%", "Degree Stream", str(student_profile.get("degree_t", "N/A"))],
        ["Employability Test (E-Test %)", f"{student_profile.get('etest_p', 0):.1f}%", "Prior Work Experience", str(student_profile.get("workex", "N/A"))],
        ["MBA / PG Aggregate %", f"{student_profile.get('mba_p', 0):.1f}%", "Specialisation", str(student_profile.get("specialisation", "N/A"))],
    ]
    profile_table = Table(profile_data, colWidths=[140, 120, 140, 130])
    profile_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1E3A8A")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F8FAFC")]),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(profile_table)
    story.append(Spacer(1, 15))

    # Actionable Coaching Recommendations
    story.append(Paragraph("Targeted Placement Cell Action Items & Guidance", h2_style))
    recs = prediction_result.get("recommendations", [])
    if not recs:
        recs = ["Profile shows strong candidate positioning. Focus on company-specific technical rounds."]

    rec_data = []
    for r in recs:
        clean_text = r.replace("**", "").replace("🚨", "[URGENT] ").replace("⚠️", "[ATTENTION] ").replace("💼", "[EXPERIENCE] ").replace("🧠", "[APTITUDE] ").replace("🛠️", "[PROJECTS] ").replace("📊", "[CERTS] ").replace("⭐", "[EXCELLENCE] ")
        rec_data.append([Paragraph(f"• {clean_text}", rec_style)])

    rec_table = Table(rec_data, colWidths=[530])
    rec_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F1F5F9")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#94A3B8")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ("PADDING", (0, 0), (-1, -1), 7),
    ]))
    story.append(rec_table)
    story.append(Spacer(1, 20))

    # Footer note
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#94A3B8"), spaceAfter=10))
    story.append(Paragraph("Confidential report generated for internal Placement Cell career coaching and student mentorship.", subtitle_style))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
